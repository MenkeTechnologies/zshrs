//! Broad differential sweep: ~570 hand-written one-liners across prompt expansion,
//! globbing, builtins, the zsh modules, diagnostics, options/traps and the stock
//! autoload functions, each run through `zshrs --zsh -f -c` and the reference zsh
//! on identical fixture directories. Every row compares stdout and exit status
//! (stderr only where the script merges it with `2>&1`).
//!
//! The rows are the ones that agree with BOTH a released zsh 5.9.2 and the
//! development-tree oracle when they were written; rows whose answer differs
//! between those two (version splits) or depends on the machine (pids, paths, the
//! clock, host name) were left out. A failing row is a regression. The sweep that
//! produced them also found and fixed: `mv`/`zstat` resolving to unloaded modules'
//! builtins for run-time command names, the stock `zmv` being replaced by a native
//! stand-in, a cached `(#m)` pattern losing `$MATCH`, and `cd` with `HOME` unset.

use std::path::Path;
use std::process::Command;

fn zshrs() -> std::path::PathBuf {
    if let Ok(p) = std::env::var("CARGO_BIN_EXE_zshrs") {
        return p.into();
    }
    Path::new(env!("CARGO_MANIFEST_DIR")).join("target/debug/zshrs")
}

/// The fixture every row runs in: a few files, a dotfile and a subdirectory.
fn fixture(tag: &str) -> std::path::PathBuf {
    let dir = std::env::temp_dir().join(format!("zshrs-sweep-{}-{tag}", std::process::id()));
    let _ = std::fs::remove_dir_all(&dir);
    for (name, body) in [
        ("a.txt", "hello\nworld\n"),
        ("b.log", "x"),
        ("c.md", ""),
        (".hid", "h"),
        ("sub/n.txt", "n"),
    ] {
        let p = dir.join(name);
        std::fs::create_dir_all(p.parent().unwrap()).unwrap();
        std::fs::write(p, body).unwrap();
    }
    dir
}

fn run(bin: &Path, flags: &[&str], script: &str, dir: &Path) -> (String, i32) {
    let out = Command::new(bin)
        .args(flags)
        .args(["-f", "-c", script])
        .current_dir(dir)
        .env_clear()
        .env("PATH", std::env::var_os("PATH").unwrap_or_default())
        .env("HOME", dir)
        .env("LANG", "en_US.UTF-8")
        .env("TERM", "xterm")
        .stdin(std::process::Stdio::null())
        .output()
        .expect("spawn shell");
    let text = String::from_utf8_lossy(&out.stdout).replace(dir.to_str().unwrap(), "D");
    (text, out.status.code().unwrap_or(-1))
}

/// Run every row of `rows` through both shells; one failure lists all divergences.
fn sweep(area: &str, rows: &[&str]) {
    let zsh = crate::oracle::zsh_path();
    if std::process::Command::new(zsh).arg("--version").output().is_err() {
        eprintln!("skip: no reference zsh");
        return;
    }
    let (rd, zd) = (fixture(&format!("{area}-ref")), fixture(&format!("{area}-rs")));
    let mut bad = Vec::new();
    for script in rows {
        let want = run(Path::new(zsh), &[], script, &rd);
        let got = run(&zshrs(), &["--zsh"], script, &zd);
        if want != got {
            bad.push(format!("  {script:?}\n    zsh  : {want:?}\n    zshrs: {got:?}"));
        }
        // Rows may create or rename files; start each from the same tree.
        let _ = std::fs::remove_dir_all(&rd);
        let _ = std::fs::remove_dir_all(&zd);
        let _ = fixture(&format!("{area}-ref"));
        let _ = fixture(&format!("{area}-rs"));
    }
    let _ = std::fs::remove_dir_all(&rd);
    let _ = std::fs::remove_dir_all(&zd);
    assert!(bad.is_empty(), "{area}: {} row(s) diverge from zsh:\n{}", bad.len(), bad.join("\n"));
}


